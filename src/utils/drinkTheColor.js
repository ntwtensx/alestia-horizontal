function buildCardGradient(colors, style = 'smooth') {
  if (!Array.isArray(colors) || colors.length === 0) {
    return 'linear-gradient(135deg, #FFFDF9 0%, #F5EBE0 100%)';
  }
  if (colors.length === 1) return colors[0];
  const angle = style === 'layered' ? 172 : style === 'sparkling' ? 150 : 135;
  const step = 100 / (colors.length - 1);
  const stops = colors.map((hex, i) => `${hex} ${Math.round(i * step)}%`).join(', ');
  return `linear-gradient(${angle}deg, ${stops})`;
}


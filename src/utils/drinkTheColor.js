function getTheColorMeta(itemName, typeKey = 'drink', isMystery = false) {
  const cleanName = String(itemName || '').trim();

  if (isMystery) {
    const colors = ['#FCE4F1', '#FFF3D6', '#DFF6FA', '#EAE4FC'];
    return {
      colors,
      border: '#DDA4C6',
      style: 'layered',
      gradient: buildCardGradient(colors, 'layered'),
      description: 'เมนูสร้างสรรค์สูตรปริศนาระดับ Create one (?) ของคาเฟ่ สุ่มราคาพิเศษ 199 - 999 เหรียญทอง'
    };
  }

  const lookupName = ALIAS_MAP[cleanName] || cleanName;
  const entry = DRINK_THE_COLOR[lookupName];

  if (entry) {
    return {
      colors: entry.c,
      border: entry.b,
      style: entry.s || 'smooth',
      gradient: buildCardGradient(entry.c, entry.s || 'smooth'),
      description: entry.d
    };
  }

  if (typeKey === 'topping' || typeKey === 'dessert') {
    const extra = resolveExtraItemVisual(cleanName, typeKey);
    return {
      colors: extra.colors,
      border: extra.border,
      style: extra.style,
      gradient: buildCardGradient(extra.colors, extra.style),
      description: extra.description
    };
  }

  // Fallback เผื่อมีเครื่องดื่มใหม่เพิ่มเข้ามาในอนาคตแล้วยังไม่ได้ตั้งสี
  const fallbackColors = ['#FBF4EC', '#EFE1D2'];
  return {
    colors: fallbackColors,
    border: '#CFAF92',
    style: 'smooth',
    gradient: buildCardGradient(fallbackColors, 'smooth'),
    description: 'เครื่องดื่มสูตรพิเศษประจำ Horizontal Cafe ชงสดใหม่ทุกแก้ว'
  };
}

